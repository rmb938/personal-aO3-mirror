// Command genreveal writes web/src/lib/reveal.gen.ts: the API's reveal query parameter as a
// TypeScript constant, from runtime.RevealParam, so the UI never handwrites its literal
// (docs/part4-ui.md, "Decisions"). Run by `go generate` in internal/web/ui, which runs it in that
// directory; it takes no arguments and writes only that one file.
package main

import (
	"fmt"
	"os"
	"strconv"

	"github.com/rmb938/personal-aO3-mirror/internal/web/api/runtime"
)

const header = `// Code generated by internal/web/ui/genreveal from runtime.RevealParam. DO NOT EDIT.

`

// output is the generated file, relative to internal/web/ui.
const output = "../../../web/src/lib/reveal.gen.ts"

func main() {
	if len(os.Args) != 1 {
		fmt.Fprintln(os.Stderr, "usage: genreveal (run by go generate in internal/web/ui; writes "+output+")")
		os.Exit(2)
	}
	if err := os.WriteFile(output, []byte(source()), 0o644); err != nil { //nolint:gosec // a generated source file, world-readable like the rest of the tree
		fmt.Fprintln(os.Stderr, "genreveal:", err)
		os.Exit(1)
	}
}

func source() string {
	return header +
		"/** The API's reveal query parameter: real fanwork on one request (docs/part2-api.md). */\n" +
		"export const REVEAL_PARAM = " + strconv.Quote(runtime.RevealParam) + ";\n\n" +
		"/** The reveal parameter's only accepted value. */\n" +
		"export const REVEAL_VALUE = " + strconv.Quote(runtime.RevealValue) + ";\n"
}
